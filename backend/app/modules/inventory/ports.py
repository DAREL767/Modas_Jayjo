from typing import Protocol

from app.modules.inventory.schemas import ProductCreate, ProductUpdate


class InventoryRepositoryPort(Protocol):
    async def create(self, product: dict, *, actor_id: str) -> dict: ...
    async def get_by_id(self, product_id: str, *, session=None) -> dict | None: ...
    async def list_products(self, *, skip: int, limit: int, active_only: bool) -> list[dict]: ...
    async def update(self, product_id: str, changes: dict) -> dict | None: ...
    async def adjust_stock(
        self, product_id: str, delta: int, reason: str, actor_id: str
    ) -> dict | None: ...


class InventoryServicePort(Protocol):
    async def create_product(self, data: ProductCreate, *, actor_id: str) -> dict: ...
    async def get_product(
        self, product_id: str, *, include_inactive: bool = False
    ) -> dict: ...
    async def list_products(self, *, skip: int, limit: int, active_only: bool) -> list[dict]: ...
    async def update_product(self, product_id: str, data: ProductUpdate) -> dict: ...
    async def adjust_stock(
        self, product_id: str, delta: int, reason: str, actor_id: str
    ) -> dict: ...
